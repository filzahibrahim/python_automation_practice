#len() returns the number of items in an object
#in string, len() counts character, punctuations and spaces

spam = "yummy"
print(len(spam)) #yummy has 5 characters so it returns 5

#in lists, it returns the number of items in it

eggs = ['yeast', 'fish', 'milk', 'bread']
print(len(eggs)) #the list has 4 items so it returns 4